export function resolveActiveLocale(mode: 'system' | 'en' | 'fa'): 'en' | 'fa' {
  if (mode === 'en' || mode === 'fa') return mode;
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('fa')) {
    return 'fa';
  }
  return 'en';
}

export function getTranslator(locale: 'en' | 'fa') {
  const dict = locale === 'fa' ? fa : en;
  return (key: keyof TranslationMap, vars?: Record<string, string | number>): string => {
    let text = dict[key] ?? en[key] ?? String(key);
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replace(`{${k}}`, String(v));
      }
    }
    return text;
  };
}
